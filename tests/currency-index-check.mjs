import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require=createRequire(import.meta.url);
const {parseCsv,calculateBurgerIndex}=require("../currency-index.js");
function csv(products){return "product,merchant,price,currency\n"+products.flatMap(([p,prices])=>prices.map((n,i)=>p+",M"+i+","+n+",EUR")).join("\n")}
const base=parseCsv(csv([["classic",[10,10,10]],["cheese",[20,20,20]],["veggie",[15,15,15]]]));
const plusTen=parseCsv(csv([["classic",[11,11,11]],["cheese",[22,22,22]],["veggie",[16.5,16.5,16.5]]]));
const uniform=calculateBurgerIndex(base,plusTen,{targetMerchants:3,maxChangePercent:20});
assert.ok(Math.abs(uniform.indexPoints-110)<1e-10);
assert.ok(Math.abs(uniform.referenceValueEur-1.1)<1e-10);
assert.equal(uniform.confidence,1);
const weakCoverage=calculateBurgerIndex(base,plusTen,{targetMerchants:6,maxChangePercent:20});
assert.ok(Math.abs(weakCoverage.indexPoints-105)<1e-10);
assert.equal(weakCoverage.coverage,.5);
const cap=calculateBurgerIndex(base,plusTen,{targetMerchants:3,maxChangePercent:2});
assert.ok(Math.abs(cap.indexPoints-102)<1e-10);
assert.equal(cap.capApplied,true);
const outlierBase=parseCsv(csv([["a",[100,100,100]],["b",[100,100,100]],["c",[100,100,100]],["d",[100,100,100]],["e",[100,100,100]]]));
const outlierNow=parseCsv(csv([["a",[100,100,100]],["b",[100,100,100]],["c",[100,100,100]],["d",[100,100,100]],["e",[1000,1000,1000]]]));
const robust=calculateBurgerIndex(outlierBase,outlierNow,{targetMerchants:3,maxChangePercent:20});
assert.equal(robust.products.filter(x=>x.outlierClipped).length,1);
assert.ok(robust.indexPoints<103);
assert.throws(()=>parseCsv("item,price\na,10"),/Colonnes requises/);
assert.throws(()=>parseCsv("product,merchant,price,currency\na,A,10,USD"),/en EUR/);
assert.throws(()=>calculateBurgerIndex(base.slice(0,2),plusTen,{minMerchants:3}),/au moins 3 commerçants/);
assert.throws(()=>calculateBurgerIndex(base,plusTen.slice(0,3),{minMerchants:3}),/mêmes produits/);
assert.throws(()=>calculateBurgerIndex(base,plusTen,{baseValueEur:0}),/supérieur à zéro/);
assert.throws(()=>calculateBurgerIndex(base,plusTen,{targetMerchants:2}),/supérieur ou égal/);
assert.equal(calculateBurgerIndex(base,plusTen,{baseValueEur:2,targetMerchants:3,maxChangePercent:20}).referenceValueEur,2.2);
console.log("PASS currency index checks");
