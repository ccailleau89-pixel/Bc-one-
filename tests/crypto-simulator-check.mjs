import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require=createRequire(import.meta.url);
const {parseCsv,runSmaBacktest}=require("../crypto-simulator.js");
const candles=parseCsv("open,close\n10,10\n10,10\n10,10\n10,11\n11,12\n12,13\n13,14\n14,15\n15,16\n16,17\n17,18");
assert.equal(candles.length,11);
assert.throws(()=>parseCsv("price\n10"),/colonnes open et close/);
assert.throws(()=>parseCsv("open,close\n0,10"),/positif/);
assert.throws(()=>runSmaBacktest(candles,{shortWindow:8,longWindow:3}),/supérieure/);
assert.throws(()=>runSmaBacktest(candles.slice(0,4),{shortWindow:3,longWindow:8}),/au moins/);
const noCost=runSmaBacktest(candles,{shortWindow:2,longWindow:3,feeBps:0,slippageBps:0});
assert.equal(noCost.signals[0].side,"achat simulé");
assert.equal(noCost.signals[0].index,4);
assert.equal(noCost.equityCurve.length,11);
assert.equal(noCost.buyAndHoldReturnPercent,80);
const withCosts=runSmaBacktest(candles,{shortWindow:2,longWindow:3,feeBps:10,slippageBps:5});
assert.ok(withCosts.strategyReturnPercent<noCost.strategyReturnPercent);
assert.ok(withCosts.maxDrawdownPercent>=0);
console.log("PASS crypto simulator checks");
